#!/usr/bin/env bash
# Refresh the Cloudflare edge ranges used by nginx and the origin firewall (H-1).
#
# Fetches https://www.cloudflare.com/ips-v4 and ips-v6, validates every line,
# rewrites infra/cloudflare/ips.txt plus the generated nginx includes, then
# reloads nginx and reapplies the firewall when the production stack is up.
# On any fetch or validation failure the existing files are left untouched.
#
# Usage:
#   sudo infra/scripts/refresh-cloudflare-ips.sh
#   sudo infra/scripts/refresh-cloudflare-ips.sh --no-firewall
#
# The weekly trendr-cloudflare-ips.timer runs the first form.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/../.." && pwd)"
CF_DIR="$REPO_ROOT/infra/cloudflare"
IPS_FILE="$CF_DIR/ips.txt"
REAL_IP_FILE="$CF_DIR/nginx-real-ip.conf"
GEO_FILE="$CF_DIR/nginx-geo.conf"
COMPOSE_FILE="$REPO_ROOT/docker-compose.prod.yml"
ENV_FILE="$REPO_ROOT/.env.production"

UPDATE_FIREWALL=1
for arg in "$@"; do
  case "$arg" in
    --no-firewall) UPDATE_FIREWALL=0 ;;
    *)
      printf 'unknown option: %s\n' "$arg" >&2
      exit 2
      ;;
  esac
done

log() { printf '[cloudflare-ips] %s\n' "$*"; }
warn() { printf '[cloudflare-ips] WARN: %s\n' "$*" >&2; }
fail() {
  printf '[cloudflare-ips] ERROR: %s\n' "$*" >&2
  exit 1
}

command -v curl >/dev/null || fail "curl is required"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

fetch() {
  curl -fsS --max-time 30 --retry 3 --retry-delay 5 "$1"
}

log "fetching Cloudflare ranges"
fetch https://www.cloudflare.com/ips-v4 >"$TMP_DIR/v4.raw" ||
  fail "could not fetch https://www.cloudflare.com/ips-v4"
fetch https://www.cloudflare.com/ips-v6 >"$TMP_DIR/v6.raw" ||
  fail "could not fetch https://www.cloudflare.com/ips-v6"

# Normalise line endings, drop blank lines and always terminate the last line.
awk '{ sub(/\r$/, ""); if ($0 ~ /^[[:space:]]*$/) next; print }' "$TMP_DIR/v4.raw" >"$TMP_DIR/v4.txt"
awk '{ sub(/\r$/, ""); if ($0 ~ /^[[:space:]]*$/) next; print }' "$TMP_DIR/v6.raw" >"$TMP_DIR/v6.txt"

[[ -s "$TMP_DIR/v4.txt" ]] || fail "Cloudflare returned an empty IPv4 list"
[[ -s "$TMP_DIR/v6.txt" ]] || fail "Cloudflare returned an empty IPv6 list"

invalid_v4="$(grep -vE '^([0-9]{1,3}\.){3}[0-9]{1,3}/([0-9]|[12][0-9]|3[0-2])$' "$TMP_DIR/v4.txt" || true)"
[[ -z "$invalid_v4" ]] || fail "ips-v4 returned an unexpected line: ${invalid_v4%%$'\n'*}"
invalid_v6="$(grep -vE '^[0-9A-Fa-f:]+/[0-9]{1,3}$' "$TMP_DIR/v6.txt" || true)"
[[ -z "$invalid_v6" ]] || fail "ips-v6 returned an unexpected line: ${invalid_v6%%$'\n'*}"

awk -F'[./]' '($1 > 255 || $2 > 255 || $3 > 255 || $4 > 255) { exit 1 }' "$TMP_DIR/v4.txt" ||
  fail "ips-v4 returned an octet above 255"
awk -F/ 'NF != 2 || $2 > 128 { exit 1 }' "$TMP_DIR/v6.txt" ||
  fail "ips-v6 returned an out-of-range prefix"

{
  printf '# Cloudflare edge ranges (https://www.cloudflare.com/ips/).\n'
  printf '# Generated by infra/scripts/refresh-cloudflare-ips.sh — do not edit by hand.\n'
  cat "$TMP_DIR/v4.txt"
  cat "$TMP_DIR/v6.txt"
} >"$TMP_DIR/ips.txt"

{
  printf '# Generated by infra/scripts/refresh-cloudflare-ips.sh — do not edit by hand.\n'
  while IFS= read -r cidr; do printf 'set_real_ip_from %s;\n' "$cidr"; done <"$TMP_DIR/v4.txt"
  while IFS= read -r cidr; do printf 'set_real_ip_from %s;\n' "$cidr"; done <"$TMP_DIR/v6.txt"
} >"$TMP_DIR/nginx-real-ip.conf"

{
  printf '# Generated by infra/scripts/refresh-cloudflare-ips.sh — do not edit by hand.\n'
  while IFS= read -r cidr; do printf '%s 1;\n' "$cidr"; done <"$TMP_DIR/v4.txt"
  while IFS= read -r cidr; do printf '%s 1;\n' "$cidr"; done <"$TMP_DIR/v6.txt"
} >"$TMP_DIR/nginx-geo.conf"

install -d "$CF_DIR"
changed=0
for pair in "ips.txt:$IPS_FILE" \
  "nginx-real-ip.conf:$REAL_IP_FILE" \
  "nginx-geo.conf:$GEO_FILE"; do
  source_file="$TMP_DIR/${pair%%:*}"
  destination="${pair#*:}"
  if [[ -f "$destination" ]] && cmp -s "$source_file" "$destination"; then
    continue
  fi
  install -m 644 "$source_file" "$destination.tmp"
  mv "$destination.tmp" "$destination"
  changed=1
  log "updated ${destination#"$REPO_ROOT"/}"
done
((changed == 1)) || log "ranges are unchanged"

reload_nginx() {
  [[ -f "$ENV_FILE" ]] || return 0
  command -v docker >/dev/null 2>&1 || return 0
  if ! docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" ps --status running nginx 2>/dev/null |
    grep -q 'nginx'; then
    log "nginx is not running; reload skipped"
    return 0
  fi
  if docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" exec -T nginx nginx -t; then
    docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" exec -T nginx nginx -s reload
    log "nginx reloaded"
  else
    warn "nginx rejected the new ranges; the on-disk config was not reloaded"
  fi
}

reload_nginx

if ((UPDATE_FIREWALL == 1)); then
  if [[ "${EUID}" -ne 0 ]]; then
    warn "not running as root; firewall rules were not updated"
  else
    bash "$SCRIPT_DIR/configure-firewall.sh"
  fi
fi
